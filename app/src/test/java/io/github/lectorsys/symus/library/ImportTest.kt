package io.github.lectorsys.symus.library

import io.github.lectorsys.symus.data.MatchState
import io.github.lectorsys.symus.data.TrackEntity
import io.github.lectorsys.symus.media.SearchHit
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Parsing what people actually have, and refusing what is not the track they
 * asked for.
 *
 * Both halves of an import fail quietly rather than loudly. A CSV split on the
 * wrong comma imports album names as artists; a matcher that accepts the first
 * plausible result fills a playlist with live versions and ten-hour loops. Both
 * produce a playlist that looks finished and is wrong, which is why the rules
 * are pinned here.
 */
class ImportTest {

    // -- links ---------------------------------------------------------------

    @Test
    fun `youtube playlist links are recognised in both forms`() {
        val plain = parseSourceLink("https://www.youtube.com/playlist?list=PL123abc")
        assertEquals(Provider.YOUTUBE, plain?.provider)
        assertEquals("PL123abc", plain?.sourceId)

        val music = parseSourceLink("https://music.youtube.com/playlist?list=OLAK5uy_x1")
        assertEquals(Provider.YOUTUBE, music?.provider)
        assertEquals("OLAK5uy_x1", music?.sourceId)

        val watch = parseSourceLink("https://www.youtube.com/watch?v=abc&list=PLzzz")
        assertEquals("PLzzz", watch?.sourceId)
    }

    /**
     * A radio mix is generated per viewer and never ends. Importing one would
     * freeze a snapshot of something that is not a playlist.
     */
    @Test
    fun `an autogenerated mix is not a playlist`() {
        assertNull(parseSourceLink("https://www.youtube.com/watch?v=abc&list=RDabc"))
    }

    @Test
    fun `spotify and apple links are recognised and say what they need`() {
        val spotify = parseSourceLink("https://open.spotify.com/playlist/37i9dQZF1DXcBWIGoYBM5M")
        assertEquals(Provider.SPOTIFY, spotify?.provider)
        assertEquals("37i9dQZF1DXcBWIGoYBM5M", spotify?.sourceId)
        assertTrue(Provider.SPOTIFY.needsCredentials)
        // Credentials the user holds, not a secret this app would have to ship.
        // The instructions have to name the redirect URI, because a Spotify app
        // registered without it rejects the sign-in with no useful message.
        assertTrue(
            Provider.SPOTIFY.setupInstructions().contains("symus://spotify-callback")
        )

        val apple = parseSourceLink(
            "https://music.apple.com/us/playlist/todays-hits/pl.f4d106fed2bd41149aaacabb233eb5eb"
        )
        assertEquals(Provider.APPLE, apple?.provider)
        assertTrue(apple!!.sourceId.startsWith("pl."))
    }

    @Test
    fun `nonsense is refused rather than guessed at`() {
        assertNull(parseSourceLink("not a link"))
        assertNull(parseSourceLink(""))
    }

    // -- files ---------------------------------------------------------------

    @Test
    fun `a quoted comma inside a title does not shift every later column`() {
        val csv = """
            Track Name,Artist Name(s),Album Name,Duration (ms)
            "Hello, Goodbye",The Beatles,Magical Mystery Tour,207000
        """.trimIndent()

        val tracks = parsePlaylistFile("export.csv", csv)
        assertEquals(1, tracks.size)
        assertEquals("Hello, Goodbye", tracks[0].title)
        assertEquals("The Beatles", tracks[0].artist)
        assertEquals("Magical Mystery Tour", tracks[0].album)
        assertEquals(207L, tracks[0].durationSec)
    }

    @Test
    fun `columns are found by name in any order`() {
        val csv = """
            ISRC,Album Name,Duration (ms),Artist Name(s),Track Name
            GBAYE0601498,Discovery,224000,Daft Punk,One More Time
        """.trimIndent()

        val tracks = parsePlaylistFile("weird.csv", csv)
        assertEquals("One More Time", tracks[0].title)
        assertEquals("Daft Punk", tracks[0].artist)
        assertEquals("GBAYE0601498", tracks[0].isrc)
        assertEquals(224L, tracks[0].durationSec)
    }

    @Test
    fun `m3u carries duration and artist`() {
        val m3u = """
            #EXTM3U
            #EXTINF:224,Daft Punk - One More Time
            /music/one-more-time.mp3
            #EXTINF:189,Kavinsky - Nightcall
            /music/nightcall.mp3
        """.trimIndent()

        val tracks = parsePlaylistFile("list.m3u", m3u)
        assertEquals(2, tracks.size)
        assertEquals("Daft Punk", tracks[0].artist)
        assertEquals("One More Time", tracks[0].title)
        assertEquals(224L, tracks[0].durationSec)
        assertEquals("Nightcall", tracks[1].title)
    }

    @Test
    fun `a plain list of lines still works`() {
        val tracks = parsePlaylistFile(
            "songs.txt",
            "Daft Punk - One More Time\nKavinsky – Nightcall\nJust A Title"
        )
        assertEquals(3, tracks.size)
        assertEquals("Daft Punk", tracks[0].artist)
        // An en dash is what a lot of exporters emit.
        assertEquals("Kavinsky", tracks[1].artist)
        // No separator: the whole line is the title rather than a bad split.
        assertNull(tracks[2].artist)
        assertEquals("Just A Title", tracks[2].title)
    }

    @Test
    fun `an unusable file yields nothing rather than throwing`() {
        assertTrue(parsePlaylistFile("empty.csv", "").isEmpty())
    }

    // -- matching ------------------------------------------------------------

    private fun hit(
        title: String,
        artist: String?,
        seconds: Long,
        id: String = title.hashCode().toString()
    ) = SearchHit(
        track = TrackEntity(
            videoId = id,
            title = title,
            artist = artist,
            duration = seconds
        ),
        channelId = null,
        channelName = artist
    )

    private val source = SourceTrack(
        position = 0,
        title = "One More Time",
        artist = "Daft Punk",
        durationSec = 320
    )

    @Test
    fun `the studio upload beats the live version and the loop`() {
        val candidates = listOf(
            hit("One More Time (Live at Alive 2007)", "Daft Punk", 330, "live"),
            hit("One More Time - Daft Punk [10 HOURS]", "Loops", 36000, "loop"),
            hit("One More Time", "Daft Punk", 320, "studio"),
            hit("One More Time (Karaoke Version)", "Sing Along", 318, "karaoke")
        )
        val best = Matching.best(source, candidates)
        assertNotNull(best)
        assertEquals("studio", best!!.videoId)
        assertEquals(MatchState.LIKELY, best.state)
    }

    @Test
    fun `a wildly wrong duration is rejected outright`() {
        val best = Matching.best(
            source,
            listOf(hit("One More Time", "Daft Punk", 36000, "loop"))
        )
        // Either nothing, or at best something flagged for a human.
        assertTrue(best == null || best.state == MatchState.UNCERTAIN)
    }

    @Test
    fun `official video noise does not stop a match`() {
        val best = Matching.best(
            source,
            listOf(hit("One More Time (Official Video) [HD]", "Daft Punk", 321, "official"))
        )
        assertEquals("official", best?.videoId)
        assertEquals(MatchState.LIKELY, best?.state)
    }

    @Test
    fun `a featured-artist suffix still matches the same song`() {
        val getLucky = SourceTrack(0, "Get Lucky", "Daft Punk", durationSec = 369)
        val best = Matching.best(
            getLucky,
            listOf(
                hit(
                    "Get Lucky (feat. Pharrell Williams and Nile Rodgers)",
                    "Daft Punk",
                    370,
                    "lucky"
                )
            )
        )
        assertEquals("lucky", best?.videoId)
    }

    /**
     * When the source asked for a live version, a live upload is the right
     * answer and the studio cut is not.
     */
    @Test
    fun `a version the source asked for is not penalised`() {
        val live = SourceTrack(0, "One More Time (Live)", "Daft Punk", durationSec = 330)
        val best = Matching.best(
            live,
            listOf(
                hit("One More Time (Live at Alive 2007)", "Daft Punk", 331, "live"),
                hit("One More Time", "Daft Punk", 320, "studio")
            )
        )
        assertEquals("live", best?.videoId)
    }

    @Test
    fun `nothing plausible returns nothing rather than the least bad thing`() {
        val best = Matching.best(
            source,
            listOf(hit("Completely Unrelated Song", "Someone Else", 200, "nope"))
        )
        assertNull(best)
    }

    @Test
    fun `an empty candidate list is not a match`() {
        assertNull(Matching.best(source, emptyList()))
    }

    @Test
    fun `counts add up the way the review screen reports them`() {
        val counts = ImportCounts(
            total = 10,
            pending = 2,
            exact = 3,
            likely = 2,
            uncertain = 1,
            unresolved = 2,
            rejected = 0
        )
        assertEquals(6, counts.matched)
        assertEquals(3, counts.needsAttention)
        assertEquals(8, counts.done)
    }
}
